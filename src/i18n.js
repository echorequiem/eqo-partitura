/** Bir anahtarı çevirir; eksikse sırasıyla İngilizce → Türkçe → anahtarın kendisi. {ad} yer tutucuları doldurulur. */
export function translate(lang, key, vars) {
  const dict = translations[lang] || translations.en;
  let s = dict[key];
  if (s === undefined) s = translations.en[key];
  if (s === undefined) s = translations.tr[key];
  if (s === undefined) return key;
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  }
  return s;
}

/** data-i18n / data-i18n-html / data-i18n-title işaretli tüm elemanları çevirir. */
export function applyStaticTranslations(lang, root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = translate(lang, el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = translate(lang, el.dataset.i18nHtml);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = translate(lang, el.dataset.i18nTitle);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = translate(lang, el.dataset.i18nPlaceholder);
  });
  document.documentElement.lang = lang;
}
